INSERT INTO work_orders (id, number, equipment_id, crew_id, created_by, assigned_to,
                          title, description, priority, status,
                          planned_start, planned_end, actual_start, actual_end,
                          failure_reason, completed_at, created_at)
SELECT
    ('33333333-0000-0000-0000-' || lpad(s.n::text, 12, '0'))::uuid,
    'Z-2026-' || lpad(s.n::text, 4, '0'),
    s.equipment_id,
    s.crew_id,
    '55555555-0000-0000-0000-000000000003'::uuid,
    s.assignee_id,
    s.title,
    s.description,
    s.priority,
    s.status,
    s.planned_start,
    s.planned_start + 2,
    CASE WHEN s.status <> 'Черновик' AND s.status <> 'Назначена' AND s.status <> 'Отменена'
         THEN s.planned_start + 1 END,
    -- Простой в часах переводится в целые дни и прибавляется к началу.
    -- Приведение к int обязательно: у date нет оператора сложения
    -- с numeric, и без него такая сумма не считается.
    CASE WHEN s.status = 'Завершена'
         THEN ((s.planned_start + 1) + (s.downtime / 24.0)::int)::timestamptz END,
    CASE WHEN s.status = 'Завершена' THEN s.failure_reason END,
    CASE WHEN s.status = 'Завершена'
         THEN ((s.planned_start + 1) + (s.downtime / 24.0)::int)::timestamptz END,
    s.planned_start::timestamptz
FROM (
    SELECT
        g.n,
        eq.id AS equipment_id,
        eq.workshop_id,
        -- Бригада назначается по цеху: у каждого цеха своя ремонтная
        -- бригада, и назначать заявку бригаде чужого цеха нельзя.
        CASE eq.workshop_id
            WHEN 'aaaaaaaa-0000-0000-0000-000000000001'::uuid THEN 'cccccccc-0000-0000-0000-000000000001'::uuid
            WHEN 'aaaaaaaa-0000-0000-0000-000000000002'::uuid THEN 'cccccccc-0000-0000-0000-000000000002'::uuid
            ELSE 'cccccccc-0000-0000-0000-000000000003'::uuid
        END AS crew_id,
        -- Исполнитель — первый человек своей бригады.
        CASE eq.workshop_id
            WHEN 'aaaaaaaa-0000-0000-0000-000000000001'::uuid THEN '55555555-0000-0000-0000-000000000004'::uuid
            WHEN 'aaaaaaaa-0000-0000-0000-000000000002'::uuid THEN '55555555-0000-0000-0000-000000000005'::uuid
            ELSE '55555555-0000-0000-0000-000000000006'::uuid
        END AS assignee_id,
        -- Приоритет. Каждый седьмой номер аварийный — из 47 заявок это
        -- семь штук, ровно столько, сколько показывает аналитика.
        CASE WHEN g.n = 47 THEN 'Высокий'
             WHEN g.n % 7 = 0 THEN 'Аварийный'
             WHEN g.n % 5 = 0 THEN 'Высокий'
             WHEN g.n % 3 = 0 THEN 'Средний'
             ELSE 'Низкий' END AS priority,
        -- Три последние заявки оставлены незакрытыми: на дашборде видны
        -- все пять статусов, а не один. Заявка Z-2026-0047 — витринная:
        -- по ней списаны материалы, поэтому она не отменена, а находится
        -- в работе: отменённая заявка с израсходованными запчастями
        -- выглядит как ошибка учёта.
        CASE WHEN g.n = 45 THEN 'Отменена'
             WHEN g.n = 46 THEN 'Назначена'
             WHEN g.n = 47 THEN 'В работе'
             ELSE 'Завершена' END AS status,
        -- Дата постановки в работу: до 27-го номера — февраль, дальше март.
