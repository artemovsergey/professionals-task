--      январь   — 12 заявок (Z-2026-0001 … Z-2026-0012)
--      февраль — 15 заявок (Z-2026-0013 … Z-2026-0027)
--      март    — 20 заявок (Z-2026-0028 … Z-2026-0047)
--      всего   — 47 заявок, счётчик work_order_counters = 47
--
--  Следующая заявка, созданная через API, получит номер Z-2026-0048 —
